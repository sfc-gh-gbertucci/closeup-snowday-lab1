GRANT USAGE ON DATABASE CLOSEUP_HOL1                      TO ROLE HOL1_BUSINESS_USER;
GRANT USAGE ON SCHEMA CLOSEUP_HOL1.ANALYTICS              TO ROLE HOL1_BUSINESS_USER;
GRANT USAGE ON SCHEMA CLOSEUP_HOL1.AI                     TO ROLE HOL1_BUSINESS_USER;
